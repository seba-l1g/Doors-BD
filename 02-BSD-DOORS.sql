-- =========================================================
-- 1. ELIMINAR TABLAS SI YA EXISTEN
-- =========================================================

BEGIN
    FOR T IN (
        SELECT COLUMN_VALUE AS NOMBRE
        FROM TABLE(SYS.ODCIVARCHAR2LIST(
            'LOGS',
            'ACCESO',
            'QR',
            'RESIDENTE_VIVIENDA',
            'VISITA',
            'VIVIENDA',
            'RESIDENTE',
            'USUARIO'
        ))
    ) LOOP
        BEGIN
            EXECUTE IMMEDIATE
                'DROP TABLE ' || T.NOMBRE || ' CASCADE CONSTRAINTS';
        EXCEPTION
            WHEN OTHERS THEN
                IF SQLCODE != -942 THEN
                    RAISE;
                END IF;
        END;
    END LOOP;
END;
/


-- 1. TABLA USUARIO
CREATE TABLE USUARIO (
    ID_USUARIO NUMBER GENERATED BY DEFAULT AS IDENTITY,
    NOMBRE VARCHAR2(100) NOT NULL,
    CORREO VARCHAR2(100) NOT NULL,
    TIPO_USUARIO VARCHAR2(20) NOT NULL,

    CONSTRAINT PK_USUARIO PRIMARY KEY (ID_USUARIO),
    CONSTRAINT UQ_USUARIO_CORREO UNIQUE (CORREO),
    CONSTRAINT CK_USUARIO_TIPO
        CHECK (TIPO_USUARIO IN ('RESIDENTE', 'VISITA'))
);

-- 2. TABLA RESIDENTE
CREATE TABLE RESIDENTE (
    ID_RESIDENTE NUMBER GENERATED BY DEFAULT AS IDENTITY,
    ID_USUARIO NUMBER NOT NULL,
    APELLIDO VARCHAR2(100) NOT NULL,
    RUT VARCHAR2(15) NOT NULL,
    TELEFONO VARCHAR2(20),
    ESTADO VARCHAR2(20) DEFAULT 'ACTIVO' NOT NULL,

    CONSTRAINT PK_RESIDENTE PRIMARY KEY (ID_RESIDENTE),
    CONSTRAINT UQ_RESIDENTE_USUARIO UNIQUE (ID_USUARIO),
    CONSTRAINT UQ_RESIDENTE_RUT UNIQUE (RUT),
    CONSTRAINT FK_RESIDENTE_USUARIO
        FOREIGN KEY (ID_USUARIO) REFERENCES USUARIO(ID_USUARIO),
    CONSTRAINT CK_RESIDENTE_ESTADO
        CHECK (ESTADO IN ('ACTIVO', 'INACTIVO'))
);

-- 3. TABLA VIVIENDA
CREATE TABLE VIVIENDA (
    ID_VIVIENDA NUMBER GENERATED BY DEFAULT AS IDENTITY,
    NUMERO VARCHAR2(10) NOT NULL,
    BLOQUE VARCHAR2(10) NOT NULL,
    PISO NUMBER NOT NULL,

    CONSTRAINT PK_VIVIENDA PRIMARY KEY (ID_VIVIENDA),
    CONSTRAINT UQ_VIVIENDA UNIQUE (NUMERO, BLOQUE, PISO)
);

-- 4. TABLA RESIDENTE_VIVIENDA
CREATE TABLE RESIDENTE_VIVIENDA (
    ID_RESIDENTE NUMBER NOT NULL,
    ID_VIVIENDA NUMBER NOT NULL,

    CONSTRAINT PK_RESIDENTE_VIVIENDA
        PRIMARY KEY (ID_RESIDENTE, ID_VIVIENDA),
    CONSTRAINT FK_RV_RESIDENTE
        FOREIGN KEY (ID_RESIDENTE) REFERENCES RESIDENTE(ID_RESIDENTE),
    CONSTRAINT FK_RV_VIVIENDA
        FOREIGN KEY (ID_VIVIENDA) REFERENCES VIVIENDA(ID_VIVIENDA)
);

-- 5. TABLA VISITA
CREATE TABLE VISITA (
    ID_VISITA NUMBER GENERATED BY DEFAULT AS IDENTITY,
    ID_USUARIO NUMBER NOT NULL,
    ID_RESIDENTE NUMBER NOT NULL,

    CONSTRAINT PK_VISITA PRIMARY KEY (ID_VISITA),
    CONSTRAINT UQ_VISITA_USUARIO UNIQUE (ID_USUARIO),
    CONSTRAINT FK_VISITA_USUARIO
        FOREIGN KEY (ID_USUARIO) REFERENCES USUARIO(ID_USUARIO),
    CONSTRAINT FK_VISITA_RESIDENTE
        FOREIGN KEY (ID_RESIDENTE) REFERENCES RESIDENTE(ID_RESIDENTE)
);

-- 6. TABLA QR
CREATE TABLE QR (
    ID_QR NUMBER GENERATED BY DEFAULT AS IDENTITY,
    ID_VISITA NUMBER NOT NULL,
    CODIGO_QR VARCHAR2(100) NOT NULL,
    FECHA_INICIO TIMESTAMP NOT NULL,
    FECHA_FIN TIMESTAMP NOT NULL,
    ESTADO VARCHAR2(20) DEFAULT 'ACTIVO' NOT NULL,

    CONSTRAINT PK_QR PRIMARY KEY (ID_QR),
    CONSTRAINT UQ_QR_CODIGO UNIQUE (CODIGO_QR),
    CONSTRAINT FK_QR_VISITA
        FOREIGN KEY (ID_VISITA) REFERENCES VISITA(ID_VISITA),
    CONSTRAINT CK_QR_ESTADO
        CHECK (ESTADO IN ('ACTIVO', 'VENCIDO', 'CANCELADO')),
    CONSTRAINT CK_QR_FECHAS
        CHECK (FECHA_FIN > FECHA_INICIO)
);

-- 7. TABLA ACCESO
-- Registra todos los intentos, incluso con QR inválidos.
CREATE TABLE ACCESO (
    ID_ACCESO NUMBER GENERATED BY DEFAULT AS IDENTITY,
    ID_QR NUMBER NULL,
    CODIGO_QR VARCHAR2(100) NOT NULL,

    CONSTRAINT PK_ACCESO PRIMARY KEY (ID_ACCESO),
    CONSTRAINT FK_ACCESO_QR
        FOREIGN KEY (ID_QR) REFERENCES QR(ID_QR)
);

-- 8. TABLA LOGS
-- Guarda el resultado y los datos del intento de acceso.
CREATE TABLE LOGS (
    ID_LOGS NUMBER GENERATED BY DEFAULT AS IDENTITY,
    ID_ACCESO NUMBER,
    ID_USUARIO NUMBER,
    TIPO_USUARIO VARCHAR2(20),
    ID_VIVIENDA NUMBER,
    FECHA_HORA TIMESTAMP DEFAULT SYSTIMESTAMP NOT NULL,
    CODIGO_QR VARCHAR2(100),
    RESULTADO VARCHAR2(12) NOT NULL,
    MOTIVO VARCHAR2(150) NOT NULL,

    CONSTRAINT PK_LOGS PRIMARY KEY (ID_LOGS),
    CONSTRAINT FK_LOGS_ACCESO
        FOREIGN KEY (ID_ACCESO) REFERENCES ACCESO(ID_ACCESO),
    CONSTRAINT FK_LOGS_USUARIO
        FOREIGN KEY (ID_USUARIO) REFERENCES USUARIO(ID_USUARIO),
    CONSTRAINT FK_LOGS_VIVIENDA
        FOREIGN KEY (ID_VIVIENDA) REFERENCES VIVIENDA(ID_VIVIENDA),
    CONSTRAINT CK_LOGS_TIPO
        CHECK (
            TIPO_USUARIO IS NULL
            OR TIPO_USUARIO IN ('RESIDENTE', 'VISITA')
        ),
    CONSTRAINT CK_LOGS_RESULTADO
        CHECK (RESULTADO IN ('AUTORIZADO', 'RECHAZADO'))
);


