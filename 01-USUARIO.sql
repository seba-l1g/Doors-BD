-- Habilitar la creación de usuarios en Oracle 12c/19c/21c/23c
ALTER SESSION SET "_ORACLE_SCRIPT" = TRUE;

-- Crear el usuario de DOOR'S
CREATE USER DOORS IDENTIFIED BY "123456"
DEFAULT TABLESPACE USERS
TEMPORARY TABLESPACE TEMP;

-- Asignar cuota y permisos básicos
ALTER USER DOORS QUOTA UNLIMITED ON USERS;

GRANT CREATE SESSION TO DOORS;
GRANT RESOURCE TO DOORS;

ALTER USER DOORS DEFAULT ROLE RESOURCE;

-- Permisos para crear los objetos del proyecto
GRANT CREATE TABLE TO DOORS;
GRANT CREATE PROCEDURE TO DOORS;
GRANT CREATE TRIGGER TO DOORS;
GRANT CREATE SEQUENCE TO DOORS;