CREATE OR REPLACE PACKAGE PKG_DOORS AS
    FUNCTION VALIDAR_QR(
        P_CODIGO IN VARCHAR2
    ) RETURN NUMBER;

    PROCEDURE GENERAR_QR(
        P_CORREO IN VARCHAR2,
        P_NOMBRE IN VARCHAR2,
        P_ID_RESIDENTE IN NUMBER,
        P_CODIGO OUT VARCHAR2
    );
END PKG_DOORS;
/

CREATE OR REPLACE PACKAGE BODY PKG_DOORS AS
    -- Validar QR y registrar acceso
    FUNCTION VALIDAR_QR(
        P_CODIGO IN VARCHAR2
    ) RETURN NUMBER
    AS
        V_CANTIDAD NUMBER;
        V_ID_QR NUMBER;
        V_HORA TIMESTAMP;
    BEGIN
        V_HORA := CAST(SYSTIMESTAMP AT TIME ZONE 'America/Santiago' AS TIMESTAMP);

        SELECT COUNT(*)
        INTO V_CANTIDAD
        FROM QR
        WHERE CODIGO_QR = TRIM(P_CODIGO) AND ESTADO = 'ACTIVO' AND FECHA_INICIO <= V_HORA AND FECHA_FIN > V_HORA;

        IF V_CANTIDAD > 0 THEN
            SELECT ID_QR
            INTO V_ID_QR
            FROM QR
            WHERE CODIGO_QR = TRIM(P_CODIGO);

            INSERT INTO ACCESO (ID_QR, CODIGO_QR)
            VALUES (V_ID_QR, TRIM(P_CODIGO));
            RETURN 1;
        ELSE
            RETURN 0;
        END IF;
    END VALIDAR_QR;

    -- Generar QR para una visita
    PROCEDURE GENERAR_QR(
        P_CORREO IN VARCHAR2,
        P_NOMBRE IN VARCHAR2,
        P_ID_RESIDENTE IN NUMBER,
        P_CODIGO OUT VARCHAR2
    )
    AS
        V_ID_USUARIO NUMBER;
        V_ID_VISITA NUMBER;
        V_ESTADO VARCHAR2(15);
        V_HORA TIMESTAMP;
    BEGIN
        IF TRIM(P_CORREO) IS NULL OR TRIM(P_NOMBRE) IS NULL THEN
            RAISE_APPLICATION_ERROR(-20001, 'Debe ingresar nombre y correo');
        END IF;

        SELECT ESTADO
        INTO V_ESTADO
        FROM RESIDENTE
        WHERE ID_RESIDENTE = P_ID_RESIDENTE;

        IF V_ESTADO <> 'ACTIVO' THEN
            RAISE_APPLICATION_ERROR(-20002, 'El residente no esta activo');
        END IF;

        INSERT INTO USUARIO (NOMBRE, CORREO, TIPO_USUARIO)
        VALUES (TRIM(P_NOMBRE), TRIM(P_CORREO), 'VISITA')
        RETURNING ID_USUARIO INTO V_ID_USUARIO;

        INSERT INTO VISITA (ID_USUARIO, ID_RESIDENTE)
        VALUES (V_ID_USUARIO, P_ID_RESIDENTE)
        RETURNING ID_VISITA INTO V_ID_VISITA;

        P_CODIGO := RAWTOHEX(SYS_GUID());
        V_HORA := CAST(SYSTIMESTAMP AT TIME ZONE 'America/Santiago' AS TIMESTAMP);

        INSERT INTO QR (ID_VISITA, CODIGO_QR, FECHA_INICIO, FECHA_FIN, ESTADO)
        VALUES (V_ID_VISITA, P_CODIGO, V_HORA, V_HORA + INTERVAL '24' HOUR, 'ACTIVO');
    END GENERAR_QR;
END PKG_DOORS;
