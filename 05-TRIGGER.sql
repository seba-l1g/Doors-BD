CREATE OR REPLACE TRIGGER TRG_LOG_ACCESO
AFTER INSERT ON ACCESO
FOR EACH ROW
DECLARE
    V_ID_USUARIO NUMBER;
    V_TIPO_USUARIO VARCHAR2(20);
    V_ID_VIVIENDA NUMBER;
BEGIN
    -- Obtener los datos de la visita asociada al QR
    SELECT U.ID_USUARIO, U.TIPO_USUARIO, RV.ID_VIVIENDA
    INTO V_ID_USUARIO, V_TIPO_USUARIO, V_ID_VIVIENDA
    FROM QR Q
    INNER JOIN VISITA VI ON Q.ID_VISITA = VI.ID_VISITA
    INNER JOIN USUARIO U ON VI.ID_USUARIO = U.ID_USUARIO
    LEFT JOIN RESIDENTE R ON VI.ID_RESIDENTE = R.ID_RESIDENTE
    LEFT JOIN RESIDENTE_VIVIENDA RV ON R.ID_RESIDENTE = RV.ID_RESIDENTE
    WHERE Q.ID_QR = :NEW.ID_QR;

    -- Registrar el acceso en LOGS
    INSERT INTO LOGS (ID_ACCESO, ID_USUARIO, TIPO_USUARIO, ID_VIVIENDA, FECHA_HORA, CODIGO_QR, RESULTADO, MOTIVO)
    VALUES (:NEW.ID_ACCESO, V_ID_USUARIO, V_TIPO_USUARIO, V_ID_VIVIENDA, SYSTIMESTAMP, :NEW.CODIGO_QR, 'AUTORIZADO', 'Acceso autorizado');
END;
